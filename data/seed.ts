function buildUsage(): UsageSnapshot[] {
  const base: Record<string, { mau: number; installs: number; tenants: number }> = {
    "prod-iq": { mau: 12400, installs: 186, tenants: 42 },
    "prod-finops": { mau: 2100, installs: 64, tenants: 18 },
    "prod-ld": { mau: 3400, installs: 51, tenants: 12 },
    "prod-openops": { mau: 980, installs: 28, tenants: 9 },
    "prod-mda": { mau: 1560, installs: 33, tenants: 11 },
    "prod-github": { mau: 420, installs: 8, tenants: 3 },
    "prod-brd": { mau: 310, installs: 6, tenants: 2 },
    "prod-hiring": { mau: 540, installs: 12, tenants: 4 },
    "prod-voice": { mau: 190, installs: 4, tenants: 1 },
  };

  const days = [
    "2026-09-16",
    "2026-09-17",
    "2026-09-18",
    "2026-09-19",
    "2026-09-20",
    "2026-09-21",
    "2026-09-22",
  ];

  const rows: UsageSnapshot[] = [];
  let i = 0;
  for (const [productId, stats] of Object.entries(base)) {
    days.forEach((date, di) => {
      const drift = 1 + (di - 3) * 0.02;
      const mau = Math.round(stats.mau * drift);
      const wau = Math.round(mau * 0.55);
      const dau = Math.round(mau * 0.18);
      rows.push({
        id: `usage-${++i}`,
        productId,
        date,
        dau,
        wau,
        mau,
        installs: stats.installs + di,
        activeTenants: stats.tenants,
        tasksExecuted: Math.round(dau * (12 + di)),
      });
    });
  }
  return rows;
}

